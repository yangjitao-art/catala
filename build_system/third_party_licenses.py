#!/usr/bin/env python3
"""Generate the third-party license manifest and a CycloneDX SBOM.

Run from the repository root with the Catala opam switch active:

    python3 build_system/third_party_licenses.py
    python3 build_system/third_party_licenses.py --bundle dist/third_party

The optional --bundle directory receives a copy of every license text found
in the opam switch (and the Debian copyright files for the system libraries),
so that release artifacts can ship the texts required by the licenses.

This file is part of the Catala compiler and is licensed under the Apache
License, Version 2.0 (see LICENSE.txt).
"""
import argparse
import datetime
import glob
import json
import os
import re
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BUILD_TOOLS = {
    "dune", "dune-configurator", "cppo", "menhir", "ocamlfind",
    "conf-ninja", "conf-npm", "conf-python-3-dev", "conf-openjdk",
    "conf-pandoc",
}

JS_ONLY = {"js_of_ocaml", "js_of_ocaml-ppx", "zarith_stubs_js"}

# Components that are not ordinary opam libraries.
EXTRA_COMPONENTS = [
    # name, version, license, role, note
    ("OCaml", "4.14.2", "LGPL-2.1-or-later WITH OCaml-LGPL-linking-exception",
     "linked", "OCaml runtime and standard library"),
    ("libgmp", "system", "LGPL-3.0-or-later OR GPL-2.0-or-later",
     "linked (dynamic)",
     "Dynamically linked through zarith; the LGPL branch must be elected."),
    ("glibc (libc, libm)", "system", "LGPL-2.1-or-later", "linked (dynamic)",
     "Dynamically linked; standard use requires shipping the license text."),
    ("Unicode Character Database", "15.0",
     "Unicode License v3", "generated data",
     "Source of the transliteration table in string_ascii_table.ml."),
    ("deps/bindlib", "local", "Apache-2.0", "vendored",
     "Independent, drop-in implementation of the Bindlib 6.0.0 API."),
    ("deps/dates-calc", "0.10.0", "Apache-2.0", "vendored",
     "Date arithmetic runtime."),
]

LICENSE_OVERRIDES = {
    # The opam metadata does not mention the linking exception, but LICENSE does.
    "ocamlgraph": "LGPL-2.1-only WITH OCaml-LGPL-linking-exception (LICENSE)",
}


def run(cmd):
    return subprocess.run(
        cmd, shell=True, capture_output=True, text=True, cwd=REPO
    ).stdout


def opam_table():
    table = {}
    for line in run(
        "opam list --installed --short --columns=name,version,license:"
    ).splitlines():
        parts = line.split(None, 2)
        if len(parts) < 2:
            continue
        lic = parts[2].strip().replace('" "', " OR ").strip('"') if len(parts) > 2 else ""
        table[parts[0]] = (parts[1], lic)
    return table


def build_graph():
    out = run("dune describe external-lib-deps 2>/dev/null")
    names = set(re.findall(r"\(([A-Za-z0-9_.+-]+) required\)", out))
    return names


def collect_licenses(bundle):
    prefix = run("opam var prefix").strip()
    doc = os.path.join(prefix, "doc")
    sources = os.path.join(prefix, ".opam-switch", "sources")
    os.makedirs(bundle, exist_ok=True)
    copied = []
    for pkg in sorted(os.listdir(doc)):
        dst = os.path.join(bundle, pkg)
        candidates = []
        for pat in ("LICENSE*", "COPYING*", "COPYRIGHT*"):
            candidates += glob.glob(os.path.join(doc, pkg, pat))
        if not candidates:
            for pat in ("LICENSE*", "COPYING*", "COPYRIGHT*"):
                candidates += glob.glob(os.path.join(sources, pkg + ".*", pat))
        if candidates:
            os.makedirs(dst, exist_ok=True)
            shutil.copyfile(candidates[0], os.path.join(dst, os.path.basename(candidates[0])))
            copied.append(pkg)
    for pkg, path in (
        ("libgmp", "/usr/share/doc/libgmp10/copyright"),
        ("glibc", "/usr/share/doc/libc6/copyright"),
    ):
        if os.path.exists(path):
            dst = os.path.join(bundle, pkg)
            os.makedirs(dst, exist_ok=True)
            shutil.copyfile(path, os.path.join(dst, "copyright"))
            copied.append(pkg)
    return copied


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", help="directory receiving the license texts")
    args = ap.parse_args()

    installed = opam_table()
    graph = build_graph()
    linked = sorted(n for n in graph if n in installed and n not in JS_ONLY)
    js = sorted(n for n in graph if n in installed and n in JS_ONLY)
    tools = sorted(n for n in BUILD_TOOLS if n in installed)

    def lic(n):
        return LICENSE_OVERRIDES.get(n, installed[n][1] or "(unknown)")

    copied = collect_licenses(args.bundle) if args.bundle else []

    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    lines = []
    w = lines.append
    w("# Third-party licenses")
    w("")
    w(f"Generated by `build_system/third_party_licenses.py` on {now}.")
    w("")
    w("This distribution is a **modified version of the Catala compiler**, "
      "distributed under the Apache License, Version 2.0 (see `LICENSE.txt` "
      "and `NOTICE`). The components below are used by the shipped binaries "
      "(`catala.exe`, `clerk.exe` and the installed plugins).")
    w("")
    w("## Linked into the binaries")
    w("")
    w("| Component | Version | License |")
    w("|---|---|---|")
    for n in linked:
        w(f"| {n} | {installed[n][0]} | {lic(n)} |")
    for name, ver, l, role, note in EXTRA_COMPONENTS:
        if role.startswith("linked"):
            w(f"| {name} | {ver} | {l} |")
    w("")
    w("LGPL components marked with a linking exception may be linked into "
      "closed binaries; their license text and the exception notice must be "
      "shipped with the binaries. `libgmp` is dual-licensed: elect the LGPL "
      "branch and keep the dynamic link.")
    w("")
    if js:
        w("## Only for the `catala-js` web interpreter")
        w("")
        w("| Component | Version | License |")
        w("|---|---|---|")
        for n in js:
            w(f"| {n} | {installed[n][0]} | {lic(n)} |")
        w("")
        w("`js_of_ocaml` is dual-licensed; the LGPL-2.1-or-later branch (with "
          "its linking exception) must be elected.")
        w("")
    w("## Build-time tools (not distributed)")
    w("")
    w("| Component | Version | License |")
    w("|---|---|---|")
    for n in tools:
        w(f"| {n} | {installed[n][0]} | {lic(n)} |")
    w("")
    w("`menhir` is GPL-2.0-only, but it is a build-time generator and its "
      "output is not linked into the binaries. `menhirLib` ships a linking "
      "exception. The `conf-*` entries are virtual packages that only check "
      "for optional system tools; they contain no code and are not shipped.")
    w("")
    w("## Vendored and generated components")
    w("")
    w("| Component | Version | License | Note |")
    w("|---|---|---|---|")
    for name, ver, l, role, note in EXTRA_COMPONENTS:
        if role in ("vendored", "generated data"):
            w(f"| {name} | {ver} | {l} | {note} |")
    w("")
    w("## What must accompany a binary release")
    w("")
    w("1. `LICENSE.txt` (Apache-2.0) and `NOTICE` (modification statement).")
    w("2. The license text of every LGPL component and its linking "
      "exception. Run this script with `--bundle DIR` to collect them.")
    w("3. The LGPL text and replaceability note for `libgmp` if it is "
      "bundled rather than taken from the operating system.")
    w("4. The Unicode License v3 notice for the generated transliteration "
      "table.")
    w("")
    w(f"Machine-readable bill of materials: `sbom.cdx.json`.")
    w("")
    w("## Regenerating")
    w("")
    w("```sh")
    w("python3 build_system/third_party_licenses.py --bundle dist/third_party")
    w("```")
    if copied:
        w("")
        w(f"License texts collected for {len(copied)} components in "
          f"`{args.bundle}`.")
    w("")

    with open(os.path.join(REPO, "THIRD_PARTY_LICENSES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    components = []

    def component(name, ver, l, role, note=""):
        comp = {
            "type": "library",
            "name": name,
            "version": ver,
            "licenses": [{"license": {"name": l}}],
            "properties": [{"name": "role", "value": role}],
        }
        if name in installed:
            comp["purl"] = f"pkg:opam/{name.lower()}@{ver}"
        components.append(comp)

    for n in linked:
        component(n, installed[n][0], lic(n), "linked")
    for n in js:
        component(n, installed[n][0], lic(n), "catala-js only")
    for n in tools:
        component(n, installed[n][0], lic(n), "build-only")
    for name, ver, l, role, note in EXTRA_COMPONENTS:
        component(name, ver, l, role)

    bom = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {
            "timestamp": datetime.datetime.now(datetime.timezone.utc)
            .isoformat()
            .replace("+00:00", "Z"),
            "component": {
                "type": "application",
                "name": "catala",
                "version": "1.3.0-fork",
                "licenses": [{"license": {"id": "Apache-2.0"}}],
            },
            "tools": [
                {
                    "vendor": "local",
                    "name": "build_system/third_party_licenses.py",
                    "version": "1",
                }
            ],
        },
        "components": components,
    }
    with open(os.path.join(REPO, "sbom.cdx.json"), "w", encoding="utf-8") as f:
        json.dump(bom, f, indent=2)
        f.write("\n")

    print(f"linked={len(linked)} js={len(js)} build={len(tools)}")
    print("wrote THIRD_PARTY_LICENSES.md and sbom.cdx.json")
    if args.bundle:
        print(f"collected {len(copied)} license texts in {args.bundle}")


if __name__ == "__main__":
    main()
